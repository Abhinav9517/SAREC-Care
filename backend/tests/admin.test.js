const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const { after, before, beforeEach, describe, it } = require('node:test')
const mongoose = require('mongoose')
const { MongoMemoryServer } = require('mongodb-memory-server')
const request = require('supertest')
const jwt = require('jsonwebtoken')

process.env.NODE_ENV = 'test'
process.env.MONGOMS_DOWNLOAD_DIR = path.join(__dirname, '..', '.mongodb-binaries')
process.env.JWT_SECRET = 'test-only-secret-that-is-long-enough-for-tests'
process.env.JWT_EXPIRES_IN = '1h'
process.env.UPLOAD_MAX_FILE_BYTES = '1024'
process.env.UPLOAD_DIR = path.join(__dirname, '..', '.test-uploads')

const { createApp } = require('../server')
const User = require('../models/User')
const Grievance = require('../models/Grievance')
const Announcement = require('../models/Announcement')
const Category = require('../models/Category')
const CampusLocation = require('../models/CampusLocation')
const AuditLog = require('../models/AuditLog')
const app = createApp()
let mongoServer
let student
let admin
let studentToken
let adminToken
const tokenFor = (user) => jwt.sign({ sub: user._id.toString(), role: user.role }, process.env.JWT_SECRET)

before(async () => { mongoServer = await MongoMemoryServer.create(); await mongoose.connect(mongoServer.getUri()) })
beforeEach(async () => {
  await Promise.all([User.deleteMany({}), Grievance.deleteMany({}), Announcement.deleteMany({}), Category.deleteMany({}), CampusLocation.deleteMany({}), AuditLog.deleteMany({})])
  student = await User.create({ name: 'Primary Student', username: 'primary.student', email: 'primary@example.com', password: 'StrongPass1' })
  admin = await User.create({ name: 'Campus Admin', username: 'campus.admin', email: 'admin@example.com', password: 'StrongPass1', role: 'admin' })
  studentToken = tokenFor(student)
  adminToken = tokenFor(admin)
})
after(async () => { await mongoose.disconnect(); if (mongoServer) await mongoServer.stop() })

describe('administrative and resolver workflows', () => {
  it('provisions a resolver, forces password replacement, and enforces role access', async () => {
    const adminLogin = await request(app).post('/api/auth/login').send({ username: 'campus.admin', password: 'StrongPass1' })
    assert.equal(adminLogin.status, 200)
    assert.equal(adminLogin.body.user.role, 'admin')
    const provision = await request(app).post('/api/admin/resolvers').set('Authorization', `Bearer ${adminToken}`).send({ username: 'maintainer.one', name: 'Maintenance One', email: 'maintainer@example.com', password: 'TempPass1' })
    assert.equal(provision.status, 201)
    const login = await request(app).post('/api/auth/login').send({ username: 'MAINTAINER.ONE', password: 'TempPass1' })
    assert.equal(login.status, 200)
    assert.equal(login.body.user.role, 'resolver')
    assert.equal(login.body.user.mustChangePassword, true)
    const resolverToken = login.body.token
    const blocked = await request(app).get('/api/grievances').set('Authorization', `Bearer ${resolverToken}`)
    assert.equal(blocked.status, 403)
    const passwordChange = await request(app).post('/api/auth/change-password').set('Authorization', `Bearer ${resolverToken}`).send({ currentPassword: 'TempPass1', newPassword: 'NewSecurePass2' })
    assert.equal(passwordChange.status, 200)
    assert.equal(passwordChange.body.user.mustChangePassword, false)
    const updatedResolverToken = passwordChange.body.token
    assert.ok(updatedResolverToken)
    assert.equal((await request(app).get('/api/grievances').set('Authorization', `Bearer ${resolverToken}`)).status, 401)
    const queue = await request(app).get('/api/grievances?all=true').set('Authorization', `Bearer ${updatedResolverToken}`)
    assert.equal(queue.status, 200)
    assert.equal((await request(app).get('/api/admin/users').set('Authorization', `Bearer ${updatedResolverToken}`)).status, 403)
    await request(app).patch(`/api/admin/users/${provision.body.data.id}/active`).set('Authorization', `Bearer ${adminToken}`).send({ active: false }).expect(200)
    assert.equal((await request(app).get('/api/grievances').set('Authorization', `Bearer ${updatedResolverToken}`)).status, 401)
  })

  it('uses database categories and locations and preserves safe directory responses', async () => {
    const category = await request(app).post('/api/admin/categories').set('Authorization', `Bearer ${adminToken}`).send({ name: 'Furniture', description: 'Tables and chairs' })
    const location = await request(app).post('/api/admin/locations').set('Authorization', `Bearer ${adminToken}`).send({ name: 'North Library' })
    assert.equal(category.status, 201)
    assert.equal(location.status, 201)
    const created = await request(app).post('/api/grievances').set('Authorization', `Bearer ${studentToken}`).send({ title: 'Broken study desk', description: 'A desk leg is loose and unsafe to use.', categoryId: category.body.data._id, locationId: location.body.data._id })
    assert.equal(created.status, 201)
    assert.equal(created.body.data.category, 'Furniture')
    assert.equal(created.body.data.location, 'North Library')
    assert.match(created.body.data.trackingId, /^CGT-/)
    const analytics = await request(app).get('/api/grievances/summary').set('Authorization', `Bearer ${adminToken}`)
    assert.equal(analytics.body.data.total, 1)
    assert.equal(analytics.body.data.categoryData.find((item) => item.name === 'Furniture').value, 1)
    const search = await request(app).get(`/api/grievances?search=${created.body.data.trackingId}&page=1&limit=10`).set('Authorization', `Bearer ${adminToken}`)
    assert.equal(search.body.data.length, 1)
    await request(app).patch(`/api/admin/categories/${category.body.data._id}`).set('Authorization', `Bearer ${adminToken}`).send({ active: false }).expect(200)
    assert.equal((await request(app).post('/api/grievances').set('Authorization', `Bearer ${studentToken}`).send({ title: 'Another study desk', description: 'A second desk leg is loose and unsafe.', categoryId: category.body.data._id, locationId: location.body.data._id })).status, 400)
    assert.equal((await request(app).delete(`/api/admin/categories/${category.body.data._id}`).set('Authorization', `Bearer ${adminToken}`)).status, 409)
    const directory = await request(app).get('/api/admin/users?role=student&page=1&limit=10').set('Authorization', `Bearer ${adminToken}`)
    assert.equal(directory.status, 200)
    assert.equal(directory.body.data[0].grievanceCount, 1)
    for (const secret of ['password', 'token', 'passwordHash', 'resetToken']) assert.equal(directory.body.data[0][secret], undefined)
    assert.equal((await request(app).get('/api/admin/users').set('Authorization', `Bearer ${studentToken}`)).status, 403)
  })

  it('permits admin announcement management and exposes only active announcements', async () => {
    const jpeg = Buffer.from([0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0xd9])
    const active = await request(app).post('/api/admin/announcements').set('Authorization', `Bearer ${adminToken}`).field('title', 'Water maintenance').field('text', 'Water will be unavailable in the west wing.').field('published', 'true').field('popup', 'true').field('startsAt', new Date().toISOString()).attach('image', jpeg, { filename: 'notice.jpg', contentType: 'image/jpeg' })
    assert.equal(active.status, 201)
    assert.equal(fs.existsSync(path.join(require('../middleware/uploadMiddleware').uploadRoot, active.body.data.imageAttachment.storageName)), true, `upload root=${require('../middleware/uploadMiddleware').uploadRoot}`)
    const hidden = await Announcement.create({ title: 'Old notice', text: 'Expired', published: true, startsAt: new Date(Date.now() - 86400000), expiresAt: new Date(Date.now() - 1000), author: admin._id })
    const studentView = await request(app).get('/api/announcements').set('Authorization', `Bearer ${studentToken}`)
    assert.equal(studentView.status, 200)
    assert.deepEqual(studentView.body.data.map((item) => item.title), ['Water maintenance'])
    assert.equal(studentView.body.data[0].acknowledgements, undefined)
    const announcementImage = await request(app).get(`/api/announcements/${active.body.data._id}/image`).set('Authorization', `Bearer ${studentToken}`)
    assert.equal(announcementImage.status, 200)
    assert.equal((await request(app).post('/api/admin/announcements').set('Authorization', `Bearer ${studentToken}`).send({ title: 'Intrusion', text: 'No.' })).status, 403)
    await request(app).post(`/api/announcements/${active.body.data._id}/acknowledge`).set('Authorization', `Bearer ${studentToken}`).expect(200)
    assert.equal((await request(app).get('/api/announcements').set('Authorization', `Bearer ${studentToken}`)).body.data[0].acknowledged, true)
    await request(app).patch(`/api/admin/announcements/${active.body.data._id}`).set('Authorization', `Bearer ${adminToken}`).send({ published: false }).expect(200)
    assert.equal((await request(app).get('/api/announcements').set('Authorization', `Bearer ${studentToken}`)).body.data.length, 0)
    await hidden.deleteOne()
  })

  it('allows resolvers to advance statuses, add comments, and students to read the audit history', async () => {
    const resolver = await User.create({ name: 'Resolver Person', username: 'resolver.person', email: 'resolver@example.com', password: 'StrongPass1', role: 'resolver' })
    const resolverToken = tokenFor(resolver)
    const created = await request(app).post('/api/grievances').set('Authorization', `Bearer ${studentToken}`).send({ title: 'Lab network offline', description: 'The laboratory network has been offline since this morning.', category: 'IT Hardware', location: 'Computer Lab' })
    const id = created.body.data._id
    const updated = await request(app).put(`/api/grievances/${id}`).set('Authorization', `Bearer ${resolverToken}`).send({ status: 'In Progress', comment: 'Network team dispatched.' })
    assert.equal(updated.status, 200)
    assert.equal(updated.body.data.statusHistory.at(-1).actorRole, 'resolver')
    assert.equal(updated.body.data.statusHistory.at(-1).comment, 'Network team dispatched.')
    await request(app).post(`/api/grievances/${id}/comments`).set('Authorization', `Bearer ${resolverToken}`).send({ text: 'The switch is being inspected.' }).expect(201)
    assert.equal((await request(app).post(`/api/grievances/${id}/comments`).set('Authorization', `Bearer ${studentToken}`).send({ text: 'Fake official note' })).status, 403)
    const details = await request(app).get(`/api/grievances/${id}`).set('Authorization', `Bearer ${studentToken}`)
    assert.equal(details.body.data.comments[0].authorRole, 'resolver')
    const resolved = await request(app).put(`/api/grievances/${id}`).set('Authorization', `Bearer ${resolverToken}`).send({ status: 'Resolved', resolution: { workPerformed: 'Replaced the switch.', notes: 'Network service restored.' } })
    assert.equal(resolved.status, 200)
    assert.equal(resolved.body.data.resolution.workPerformed, 'Replaced the switch.')
    assert.equal(resolved.body.data.resolution.resolvedBy.toString(), resolver._id.toString())
    const correction = await request(app).put(`/api/grievances/${id}`).set('Authorization', `Bearer ${resolverToken}`).send({ status: 'Resolved', resolution: { notes: 'Network service restored and tested.' } })
    assert.equal(correction.body.data.resolutionHistory.length, 2)
    assert.equal(correction.body.data.resolutionHistory[0].notes, 'Network service restored.')
    assert.equal(correction.body.data.resolution.notes, 'Network service restored and tested.')
    const evidence = Buffer.from([0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0xd9])
    const evidenceResponse = await request(app).post(`/api/grievances/${id}/resolution-evidence`).set('Authorization', `Bearer ${resolverToken}`).attach('attachments', evidence, { filename: 'repaired.jpg', contentType: 'image/jpeg' })
    assert.equal(evidenceResponse.status, 201)
    const adminEvidence = await request(app).post(`/api/grievances/${id}/resolution-evidence`).set('Authorization', `Bearer ${adminToken}`).attach('attachments', evidence, { filename: 'admin-review.jpg', contentType: 'image/jpeg' })
    assert.equal(adminEvidence.status, 201)
    const privateEvidence = await request(app).get(`/api/grievances/${id}/attachments/${evidenceResponse.body.data[0].storageName}`).set('Authorization', `Bearer ${studentToken}`)
    assert.equal(privateEvidence.status, 200)
    const otherStudent = await User.create({ name: 'Other Student', username: 'other.student', email: 'other@example.com', password: 'StrongPass1' })
    const deniedEvidence = await request(app).get(`/api/grievances/${id}/attachments/${evidenceResponse.body.data[0].storageName}`).set('Authorization', `Bearer ${tokenFor(otherStudent)}`)
    assert.equal(deniedEvidence.status, 404)
    assert.equal((await request(app).put(`/api/grievances/${id}`).set('Authorization', `Bearer ${resolverToken}`).send({ status: 'Pending' })).status, 400)
    assert.equal((await request(app).get(`/api/grievances/${id}`).set('Authorization', `Bearer ${studentToken}`)).body.data.statusHistory.length, 3)
  })
})
